#!/usr/bin/env bash
# 03.4 generate check. Re-runnable. The cache is removed at the start.
# Run this from start/ after the generate blocks, or from solution/.
set -euo pipefail

cd "$(dirname "$0")"
rm -rf .terragrunt-cache

pass() {
  echo "PASS  $*"
}

echo "== 1. Generate blocks."
if ! grep -q 'generate "versions"' terragrunt.hcl; then
  echo 'FAIL  add generate "versions"'
  exit 1
fi
if ! grep -q 'generate "provider"' terragrunt.hcl; then
  echo 'FAIL  add generate "provider"'
  exit 1
fi
if ! grep -q 'overwrite_terragrunt' terragrunt.hcl; then
  echo "FAIL  set if_exists = \"overwrite_terragrunt\""
  exit 1
fi
pass "generate blocks"

echo "== 2. Engine."
version_log="$(mktemp)"
terragrunt --no-color run -- version 2>&1 | tee "$version_log"
if ! grep -q "Terraform v1\.17\." "$version_log"; then
  echo "FAIL  engine was not Terraform 1.17.x"
  rm -f "$version_log"
  exit 1
fi
if grep -q "OpenTofu" "$version_log"; then
  echo "FAIL  OpenTofu ran. terraform_binary should select Terraform."
  rm -f "$version_log"
  exit 1
fi
pass "engine is Terraform 1.17.x"
rm -f "$version_log"

echo "== 3. Plan, then plan again so overwrite_terragrunt runs twice."
plan_once() {
  local plan_log
  plan_log="$(mktemp)"
  terragrunt --no-color --non-interactive run -- plan -input=false -no-color 2>&1 | tee "$plan_log"
  if ! grep -q "Plan: 3 to add, 0 to change, 0 to destroy." "$plan_log"; then
    echo "FAIL  plan did not report 3 adds"
    rm -f "$plan_log"
    exit 1
  fi
  rm -f "$plan_log"
}
plan_once
pass "plan"
plan_once
pass "second plan"

echo "== 4. Generated files in the working copy."
versions="$(find .terragrunt-cache -type f -name versions.tf -print -quit)"
provider="$(find .terragrunt-cache -type f -name provider.tf -print -quit)"
if [[ -z "$versions" || -z "$provider" ]]; then
  echo "FAIL  versions.tf or provider.tf was not generated"
  exit 1
fi
if ! grep -q "Generated by Terragrunt" "$versions"; then
  echo "FAIL  versions.tf has no Terragrunt signature"
  exit 1
fi
if ! grep -q "Generated by Terragrunt" "$provider"; then
  echo "FAIL  provider.tf has no Terragrunt signature"
  exit 1
fi
if ! grep -q '>= 1.17.0, < 1.18.0' "$versions"; then
  echo "FAIL  versions.tf does not pin Terraform 1.17"
  exit 1
fi
for provider_source in hashicorp/local hashicorp/null hashicorp/random; do
  if ! grep -q "$provider_source" "$versions"; then
    echo "FAIL  versions.tf is missing ${provider_source}"
    exit 1
  fi
done
for provider_name in local null random; do
  if ! grep -q "provider \"${provider_name}\"" "$provider"; then
    echo "FAIL  provider.tf is missing provider \"${provider_name}\""
    exit 1
  fi
done
pass "generated versions: $versions"
pass "generated provider: $provider"

echo "== 5. Inputs match the module variables."
terragrunt hcl validate --inputs --strict --tf-path terraform --no-color
pass "inputs"

echo "== 6. Apply, output, destroy."
terragrunt --no-color --non-interactive run -- apply -auto-approve -input=false -no-color
output_log="$(mktemp)"
terragrunt --no-color output -no-color | tee "$output_log"
if ! grep -Eq 'name = "lab-[a-z]+-[a-z]+"' "$output_log"; then
  echo "FAIL  output name was not a lab- pet name"
  rm -f "$output_log"
  exit 1
fi
if ! grep -qx 'note = "generated provider files"' "$output_log"; then
  echo "FAIL  note output"
  rm -f "$output_log"
  exit 1
fi
pass "apply"
rm -f "$output_log"
terragrunt --no-color --non-interactive run -- destroy -auto-approve -input=false -no-color
pass "destroy"

echo "PASS  03.4 generate"
