#!/usr/bin/env bash
# 07.3 values check. Re-runnable. Generated stacks and caches are removed first.
# Run this from start/ after the TODO, or from solution/.
set -euo pipefail

cd "$(dirname "$0")"

pass() {
  echo "PASS  $*"
}

code_grep() {
  local file="$1"
  local pattern="$2"
  grep -E "$pattern" "$file" | grep -Eqv '^[[:space:]]*#'
}

need() {
  local file="$1"
  local pattern="$2"
  local message="$3"
  if ! code_grep "$file" "$pattern"; then
    echo "FAIL  ${message}"
    exit 1
  fi
}

forbid() {
  local file="$1"
  local pattern="$2"
  local message="$3"
  if code_grep "$file" "$pattern"; then
    echo "FAIL  ${message}"
    exit 1
  fi
}

assert_tg() {
  local version_log
  version_log="$(mktemp)"
  terragrunt --version >"$version_log" 2>&1
  if ! grep -q "v1\.2\." "$version_log"; then
    echo "FAIL  terragrunt was not 1.2.x"
    cat "$version_log"
    rm -f "$version_log"
    exit 1
  fi
  pass "terragrunt 1.2.x"
  rm -f "$version_log"
}

assert_engine() {
  local dir="$1"
  local version_log
  version_log="$(mktemp)"
  (
    cd "$dir"
    terragrunt --no-color run -- version
  ) >"$version_log" 2>&1
  if ! grep -q "Terraform v1\.17\." "$version_log"; then
    echo "FAIL  ${dir}: engine was not Terraform 1.17.x"
    cat "$version_log"
    rm -f "$version_log"
    exit 1
  fi
  if grep -q "OpenTofu" "$version_log"; then
    echo "FAIL  ${dir}: OpenTofu ran. terraform_binary should select Terraform."
    rm -f "$version_log"
    exit 1
  fi
  pass "${dir} engine"
  rm -f "$version_log"
}

clean_runtime() {
  find . -type d \( -name .terragrunt-cache -o -name .terraform -o -name .terragrunt-stack \) -prune -exec rm -rf {} +
  find . \( -name '*.tfstate' -o -name '*.tfstate.*' \) -delete
}

plan_count() {
  local file="$1"
  grep -c "Plan: 3 to add, 0 to change, 0 to destroy." "$file" || true
}


clean_runtime

echo "== 1. Terragrunt 1.2.x and formatted HCL."
assert_tg
terragrunt hcl fmt --check --no-color
pass "fmt"

echo "== 2. Values on the unit block, and an autoinclude for the network output."
need root.hcl '^terraform_binary[[:space:]]*=[[:space:]]*"terraform"' \
  'root.hcl should set terraform_binary = "terraform"'
need units/record/terragrunt.hcl 'environment[[:space:]]*=[[:space:]]*values\.environment' \
  'the record unit should read values.environment'
need units/record/terragrunt.hcl 'prefix[[:space:]]*=[[:space:]]*values\.prefix' \
  'the record unit should read values.prefix'
need units/record/terragrunt.hcl 'note[[:space:]]*=[[:space:]]*values\.note' \
  'the record unit should read values.note'
need units/record/terragrunt.values.hcl 'prefix[[:space:]]*=[[:space:]]*"def"' \
  'keep the default prefix = "def"'
need live/terragrunt.stack.hcl 'unit[[:space:]]+"plain"' \
  'keep the plain unit'
if code_grep live/terragrunt.stack.hcl 'unit[[:space:]]+"plain"' && \
  awk '/unit "plain"/,/^}/' live/terragrunt.stack.hcl | grep -Eq '^[[:space:]]*values[[:space:]]*='; then
  echo "FAIL  leave values off the plain unit so the default terragrunt.values.hcl is copied"
  exit 1
fi
need live/terragrunt.stack.hcl 'prefix[[:space:]]*=[[:space:]]*"net"' \
  'set network prefix = "net"'
need live/terragrunt.stack.hcl 'note[[:space:]]*=[[:space:]]*"network unit"' \
  'set network note = "network unit"'
need live/terragrunt.stack.hcl 'prefix[[:space:]]*=[[:space:]]*"svc"' \
  'set service prefix = "svc"'
need live/terragrunt.stack.hcl 'autoinclude' \
  'add an autoinclude block on the service unit'
need live/terragrunt.stack.hcl 'config_path[[:space:]]*=[[:space:]]*unit\.network\.path' \
  'set config_path = unit.network.path'
need live/terragrunt.stack.hcl 'note[[:space:]]*=[[:space:]]*dependency\.network\.outputs\.name' \
  'set the autoinclude input note = dependency.network.outputs.name'
need live/terragrunt.stack.hcl 'mock_outputs_allowed_terraform_commands[[:space:]]*=[[:space:]]*\[[[:space:]]*"validate"[[:space:]]*,[[:space:]]*"plan"[[:space:]]*\]' \
  'allow mocks for validate and plan only'
forbid live/terragrunt.stack.hcl '"TODO"' \
  'replace the TODO values'
pass "values and autoinclude"

echo "== 3. Generate. plain keeps the default file. network replaces it."
(
  cd live
  terragrunt --no-color stack generate
)
if ! cmp -s units/record/terragrunt.values.hcl live/.terragrunt-stack/plain/terragrunt.values.hcl; then
  echo "FAIL  plain/terragrunt.values.hcl is not the unit default"
  echo "---- unit default ----"
  cat units/record/terragrunt.values.hcl
  echo "---- generated plain ----"
  cat live/.terragrunt-stack/plain/terragrunt.values.hcl
  exit 1
fi
if ! grep -q 'Auto-generated by the terragrunt.stack.hcl' live/.terragrunt-stack/network/terragrunt.values.hcl; then
  echo "FAIL  network values should be the generated file"
  cat live/.terragrunt-stack/network/terragrunt.values.hcl
  exit 1
fi
need live/.terragrunt-stack/network/terragrunt.values.hcl 'prefix[[:space:]]*=[[:space:]]*"net"' \
  'generated network prefix should be net'
need live/.terragrunt-stack/service/terragrunt.autoinclude.hcl 'config_path[[:space:]]*=[[:space:]]*"\.\./network"' \
  'generated dependency config_path should be ../network'
pass "generated values"

echo "== 4. Cold plan uses the mock. Apply wires the network name."
plan_log="$(mktemp)"
(
  cd live
  terragrunt --no-color --non-interactive stack run -- plan -input=false -no-color
) >"$plan_log" 2>&1
if [[ "$(plan_count "$plan_log")" -ne 3 ]]; then
  echo "FAIL  expected three plans of 3 adds, got $(plan_count "$plan_log")"
  cat "$plan_log"
  rm -f "$plan_log"
  exit 1
fi
if ! grep -q 'mock-network-name' "$plan_log"; then
  echo "FAIL  service plan did not use the mock network name"
  cat "$plan_log"
  rm -f "$plan_log"
  exit 1
fi
if ! grep -q 'default note' "$plan_log"; then
  echo "FAIL  plain plan did not use the default note"
  cat "$plan_log"
  rm -f "$plan_log"
  exit 1
fi
pass "cold plan"
rm -f "$plan_log"

(
  cd live
  terragrunt --no-color --non-interactive stack run -- apply -input=false -no-color
)
out="$(mktemp)"
(
  cd live
  terragrunt --no-color stack output --format json
) >"$out"
python3 - "$out" << 'PY'
import json, sys
data = json.load(open(sys.argv[1]))
plain, network, service = data["plain"], data["network"], data["service"]
errors = []
if plain["prefix"] != "def" or plain["note"] != "default note":
    errors.append(f"plain values were {plain['prefix']!r} {plain['note']!r}")
if network["prefix"] != "net" or network["note"] != "network unit":
    errors.append(f"network values were {network['prefix']!r} {network['note']!r}")
if service["prefix"] != "svc":
    errors.append(f"service prefix was {service['prefix']!r}")
if service["note"] != network["name"]:
    errors.append(f"service note {service['note']!r} is not network name {network['name']!r}")
if service["note"] == "mock-network-name":
    errors.append("service note is still the mock")
if not network["name"].startswith("net-"):
    errors.append(f"network name was {network['name']!r}")
if errors:
    print("FAIL  " + "; ".join(errors))
    sys.exit(1)
print(f"PASS  service note is {network['name']}")
PY
rm -f "$out"
assert_engine live/.terragrunt-stack/network

echo "== 5. Destroy, then clean the generated stack."
(
  cd live
  terragrunt --no-color --non-interactive stack run -- destroy -input=false -no-color
  terragrunt --no-color stack clean
)
[[ ! -d live/.terragrunt-stack ]]
pass "destroy and clean"

clean_runtime
echo "PASS  07.3 values"
