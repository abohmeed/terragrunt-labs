#!/usr/bin/env bash
# 05.1 remote state check. Re-runnable. The cache and local state are removed first.
# Run this from start/ after the TODO, or from solution/.
set -euo pipefail

cd "$(dirname "$0")"
rm -rf dev/.terragrunt-cache prod/.terragrunt-cache state

pass() {
  echo "PASS  $*"
}

need() {
  local file="$1"
  local pattern="$2"
  local message="$3"
  if ! grep -Eq "$pattern" "$file"; then
    echo "FAIL  ${message}"
    exit 1
  fi
}

forbid() {
  local file="$1"
  local pattern="$2"
  local message="$3"
  if grep -Eq "$pattern" "$file"; then
    echo "FAIL  ${message}"
    exit 1
  fi
}

echo "== 1. HCL is formatted."
terragrunt hcl fmt --check --no-color
pass "fmt"

echo "== 2. remote_state uses the local backend and a path outside the unit."
need root.hcl 'backend[[:space:]]*=[[:space:]]*"local"' \
  'set remote_state.backend to "local"'
need root.hcl 'path[[:space:]]*=[[:space:]]*"backend\.tf"' \
  'generate backend.tf from remote_state'
need root.hcl 'if_exists[[:space:]]*=[[:space:]]*"overwrite_terragrunt"' \
  'set generate.if_exists to overwrite_terragrunt'
need root.hcl 'get_parent_terragrunt_dir\(\)' \
  'build an absolute state path with get_parent_terragrunt_dir()'
need root.hcl 'path_relative_to_include\(\)' \
  'give each unit its own state file with path_relative_to_include()'
need root.hcl '^terraform_binary[[:space:]]*=[[:space:]]*"terraform"' \
  'root.hcl should set terraform_binary = "terraform"'
forbid root.hcl 'path[[:space:]]*=[[:space:]]*"TODO"' \
  'replace the TODO state path'
forbid dev/terragrunt.hcl '^terraform_binary[[:space:]]*=' \
  'leave terraform_binary in root.hcl'
forbid prod/terragrunt.hcl '^terraform_binary[[:space:]]*=' \
  'leave terraform_binary in root.hcl'
pass "remote_state"

run_unit() {
  local dir="$1"
  local environment="$2"
  local prefix="$3"
  local state_file
  state_file="$(pwd)/state/${dir}/terraform.tfstate"

  echo "== ${dir}: engine"
  local version_log
  version_log="$(mktemp)"
  (
    cd "$dir"
    terragrunt --no-color run -- version
  ) 2>&1 | tee "$version_log"
  if ! grep -q "Terraform v1\.17\." "$version_log"; then
    echo "FAIL  ${dir}: engine was not Terraform 1.17.x"
    rm -f "$version_log"
    exit 1
  fi
  if grep -q "OpenTofu" "$version_log"; then
    echo "FAIL  ${dir}: OpenTofu ran. terraform_binary should select Terraform."
    rm -f "$version_log"
    exit 1
  fi
  pass "${dir} engine"
  rm -f "$version_log"

  echo "== ${dir}: render"
  local render_log
  render_log="$(mktemp)"
  (
    cd "$dir"
    terragrunt --no-color render
  ) | tee "$render_log"
  if ! grep -Fq "path = \"${state_file}\"" "$render_log"; then
    echo "FAIL  ${dir}: render path is not ${state_file}"
    rm -f "$render_log"
    exit 1
  fi
  need "$render_log" 'backend[[:space:]]*=[[:space:]]*"local"' "${dir} render: local backend"
  need "$render_log" "environment[[:space:]]*=[[:space:]]*\"${environment}\"" "${dir} render: environment"
  need "$render_log" "prefix[[:space:]]*=[[:space:]]*\"${prefix}\"" "${dir} render: prefix"
  need "$render_log" 'note[[:space:]]*=[[:space:]]*"local remote state"' "${dir} render: note"
  pass "${dir} render"
  rm -f "$render_log"

  echo "== ${dir}: inputs match the module variables."
  (
    cd "$dir"
    terragrunt hcl validate --inputs --strict --tf-path terraform --no-color
  )
  pass "${dir} inputs"

  echo "== ${dir}: plan and apply"
  local plan_log
  plan_log="$(mktemp)"
  (
    cd "$dir"
    terragrunt --no-color --non-interactive run -- plan -input=false -no-color
  ) 2>&1 | tee "$plan_log"
  if ! grep -q "Plan: 3 to add, 0 to change, 0 to destroy." "$plan_log"; then
    echo "FAIL  ${dir}: plan did not report 3 adds"
    rm -f "$plan_log"
    exit 1
  fi
  pass "${dir} plan"
  rm -f "$plan_log"

  (
    cd "$dir"
    terragrunt --no-color --non-interactive run -- apply -auto-approve -input=false -no-color
  )

  if [[ ! -f "$state_file" ]]; then
    echo "FAIL  ${dir}: state file missing at ${state_file}"
    exit 1
  fi
  if grep -Rql "\"prefix\": \"${prefix}\"" "${dir}/.terragrunt-cache"; then
    echo "FAIL  ${dir}: state content is inside .terragrunt-cache"
    exit 1
  fi
  if ! grep -Fq "\"prefix\": \"${prefix}\"" "$state_file"; then
    echo "FAIL  ${dir}: state file does not record prefix ${prefix}"
    exit 1
  fi

  local backend_file
  backend_file="$(find "${dir}/.terragrunt-cache" -name backend.tf -print | head -n 1)"
  if [[ -z "${backend_file}" ]]; then
    echo "FAIL  ${dir}: remote_state did not generate backend.tf"
    exit 1
  fi
  need "$backend_file" 'Generated by Terragrunt' "${dir}: backend.tf signature"
  need "$backend_file" 'backend "local"' "${dir}: generated backend is local"
  if ! grep -Fq "$state_file" "$backend_file"; then
    echo "FAIL  ${dir}: backend.tf path is not ${state_file}"
    exit 1
  fi
  pass "${dir} state file"

  echo "== ${dir}: output still works after the cache is removed"
  rm -rf "${dir}/.terragrunt-cache"
  local output_log
  output_log="$(mktemp)"
  (
    cd "$dir"
    terragrunt --no-color output -no-color
  ) | tee "$output_log"
  need "$output_log" "^environment = \"${environment}\"\$" "${dir}: environment output"
  need "$output_log" "^prefix = \"${prefix}\"\$" "${dir}: prefix output"
  need "$output_log" '^note = "local remote state"$' "${dir}: note output"
  need "$output_log" "^name = \"${prefix}-[a-z]+-[a-z]+\"\$" "${dir}: name output"
  pass "${dir} output after cache removal"
  rm -f "$output_log"
}

run_unit dev dev dev-lab
run_unit prod prod prod-lab

echo "== dev and prod kept separate state files"
if ! grep -Fq '"prefix": "dev-lab"' state/dev/terraform.tfstate; then
  echo "FAIL  prod reused the dev state file"
  exit 1
fi
if ! grep -Fq '"prefix": "prod-lab"' state/prod/terraform.tfstate; then
  echo "FAIL  prod state file does not record prefix prod-lab"
  exit 1
fi
pass "separate state files"

echo "== destroy"
for dir in dev prod; do
  (
    cd "$dir"
    terragrunt --no-color --non-interactive run -- destroy -auto-approve -input=false -no-color
  )
  pass "${dir} destroy"
done

rm -rf state dev/.terragrunt-cache prod/.terragrunt-cache
echo "PASS  05.1 remote state"
